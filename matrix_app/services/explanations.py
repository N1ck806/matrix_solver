# Публичная функция
# =============================================================================

def explain(operation: str, payload: dict[str, Any] | None = None) -> str:
    """Вернуть пояснение для операции.

    Параметры:
        operation — код операции ('determinant', 'rank', 'inverse', ...);
        payload   — словарь с результатом и контекстом; используется
                    для подбора более точного динамического пояснения.

    Возвращает строку с Markdown-разметкой. Если для операции нет
    пояснения, возвращает пустую строку (шаблон не покажет блок).
    """
    base = _EXPLANATIONS.get(operation, "")

    if payload:
        dynamic = _dynamic_explanation(operation, payload)
        if dynamic:
            if base:
                return f"{dynamic}\n\n---\n\n{base}"
            return dynamic

    return base


def has_explanation(operation: str) -> bool:
    """Есть ли пояснение для данной операции."""
    return operation in _EXPLANATIONS


def list_operations() -> list[str]:
    """Список операций, для которых есть пояснение."""
    return sorted(_EXPLANATIONS.keys())