# =============================================================================
# Динамические пояснения (зависят от контекста)
# =============================================================================

def _dynamic_explanation(operation: str, payload: dict[str, Any]) -> str | None:
    """Пояснения, которые зависят от конкретного результата."""
    # Определитель — объясняем частные случаи.
    if operation == "determinant":
        value = payload.get("value")
        if value is not None:
            if value == 0:
                return (
                    "**Определитель равен нулю.** Это означает, что:\n\n"
                    "• матрица **вырожденная** (необратимая);\n"
                    "• строки и столбцы **линейно зависимы** — одну можно "
                    "выразить через другие;\n"
                    "• система Ax = b либо несовместна, либо имеет "
                    "бесконечно много решений (никогда — единственное);\n"
                    "• линейное преобразование **сжимает** пространство "
                    "в подпространство меньшей размерности.\n\n"
                    "Геометрически: объём образа равен нулю."
                )
            if value == 1:
                return (
                    "**Определитель равен 1.** Линейное преобразование "
                    "**сохраняет объём** и ориентацию. Примерами служат "
                    "матрицы поворотов и сдвигов."
                )
            if value == -1:
                return (
                    "**Определитель равен −1.** Преобразование сохраняет "
                    "объём, но **меняет ориентацию** — это отражение "
                    "(например, зеркало или инверсия оси)."
                )
        return None

    # Ранг — сравниваем с размером.
    if operation == "rank":
        value = payload.get("value")
        rows = payload.get("rows")
        cols = payload.get("cols")
        if value is not None and rows and cols:
            if value == min(rows, cols):
                return (
                    f"**Ранг = {value}** — это **максимально возможное "
                    f"значение** для матрицы {rows}×{cols}. "
                    "Значит, строки (и столбцы) **линейно независимы**, "
                    "матрица имеет **полный ранг**."
                )
            if value == 0:
                return (
                    "**Ранг = 0** — матрица **нулевая**, все её строки "
                    "и столбцы — нулевые векторы."
                )
        return None

    # Обратная — если её посчитали, det(A) ≠ 0.
    if operation == "inverse":
        return (
            "**Обратная матрица существует**, потому что det(A) ≠ 0. "
            "Это значит, что:\n\n"
            "• линейное преобразование **обратимо**;\n"
            "• система Ax = b имеет **единственное решение** x = A⁻¹b "
            "при любой правой части b;\n"
            "• столбцы A **линейно независимы** и образуют базис;\n"
            "• rank(A) = n."
        )

    # СЛАУ — по типу решения.
    if operation in {"solve_gauss", "solve_gauss_jordan", "solve_cramer", "solve_inverse"}:
        kind = payload.get("kind")
        if kind == "unique":
            return (
                "**Система имеет единственное решение.** Это означает, "
                "что:\n\n"
                "• det(A) ≠ 0 (для квадратной системы);\n"
                "• rank(A) = rank([A | b]) = n (число неизвестных);\n"
                "• столбцы A линейно независимы;\n"
                "• решение можно найти любым корректным методом — "
                "результат один и тот же."
            )
        if kind == "infinite":
            return (
                "**Система имеет бесконечно много решений.** Признаки:\n\n"
                "• rank(A) = rank([A | b]) < n;\n"
                "• есть **свободные переменные** (им можно придавать "
                "произвольные значения);\n"
                "• решения образуют **аффинное подпространство** размерности "
                "n − rank(A);\n"
                "• общее решение = частное + линейная комбинация ФСР "
                "(фундаментальной системы решений однородной системы)."
            )
        if kind == "none":
            return (
                "**Система несовместна** — решений нет. Признак:\n\n"
                "• rank(A) ≠ rank([A | b]) — обычно rank([A|b]) = "
                "rank(A) + 1;\n"
                "• в системе есть **противоречивое уравнение** вида "
                "0 = c, где c ≠ 0;\n"
                "• геометрически: гиперплоскости, задаваемые уравнениями, "
                "не пересекаются в одной точке."
            )
        return None

    return None


